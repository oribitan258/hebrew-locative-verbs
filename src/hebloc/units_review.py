"""Human review of extracted units: real before/after examples per corpus, incl. difficult cases.

Writes a Markdown file showing, for each example: reference, sent_id, exact source location,
the raw source slice, the normalized text, and the flags that fired. Examples are random (seeded)
plus targeted selections by flag, so every rule is seen in action on real data.
"""

from __future__ import annotations

from pathlib import Path

import duckdb

from hebloc.paths import CORPORA

# Flags worth showing explicitly per corpus (each gets up to N examples if present).
TARGETED = {
    "mikra": ["ketiv_qere", "qere_only", "ketiv_only", "aramaic", "parasha_marker", "accent_quotes_removed"],
    "hazal": ["enumerator_removed", "html_entities_decoded", "long"],
    "medieval": ["citation_plus_to_parens", "prefix_R3", "prefix_unresolved", "enumerator_removed", "long"],
    "haskala": ["html_tags_removed", "sic_marker_removed", "quote_brackets_removed", "braces_removed",
                "hash_marker_removed", "separator_removed", "long"],
    "modern": ["haaretz_header_removed", "prefix_R1", "prefix_R2", "prefix_R3", "token_R4",
               "prefix_unresolved:hyphen_hebrew", "prefix_unresolved:hyphen_punct",
               "prefix_unresolved:punct", "img_marker_removed", "contains_url", "long"],
}


def _fmt(row: dict) -> str:
    flags = ", ".join(row["norm_flags"]) or "—"
    alt = f"\n- **Ketiv reading (`text_norm_alt`)**: `{row['text_norm_alt']}`" if row.get("text_norm_alt") else ""
    raw = row["text_raw"] if len(row["text_raw"]) < 700 else row["text_raw"][:700] + " …"
    norm = row["text_norm"] if len(row["text_norm"]) < 700 else row["text_norm"][:700] + " …"
    return (
        f"**{row['ref']}** · `{row['sent_id']}` · {row['unit_type']}"
        f"{' · Aramaic: ' + row['aramaic'] if row.get('aramaic') else ''}\n"
        f"- Source: `{row['rel_path']}` line {row['line_no']}, chars {row['char_start']}–{row['char_end']}\n"
        f"- **Raw**: `{raw}`\n- **Norm**: `{norm}`{alt}\n- Flags: {flags}\n"
    )


def write_review(units_root: Path, catalog: Path, out: Path, per_corpus: int = 5, per_flag: int = 2, seed: int = 7) -> Path:
    con = duckdb.connect()
    parts = ["# M2 sample review — real before/after examples", "",
             "Generated by `uv run hebloc prepare --sample …` (`hebloc.units_review`). Each example shows the exact "
             "source location; `Raw` is the untouched source slice, `Norm` the model input.", ""]
    for cid in CORPORA:
        glob = (units_root / cid / "*.parquet").as_posix()
        if not list((units_root / cid).glob("*.parquet")):
            continue
        base = (f"SELECT u.*, d.rel_path FROM read_parquet('{glob}') u "
                f"JOIN read_parquet('{catalog.as_posix()}') d USING (doc_id)")
        n = con.execute(f"SELECT count(*) FROM ({base})").fetchone()[0]
        parts += [f"## {cid} ({n:,} sample units)", "", "### Random examples", ""]
        rows = con.execute(f"{base} WHERE NOT is_empty_norm ORDER BY hash(sent_id || '{seed}') LIMIT {per_corpus}").df()
        parts += [_fmt(r) for r in rows.to_dict("records")]
        for flag in TARGETED.get(cid, []):
            if flag == "long":  # would need parse-time pieces at the v1 200-token cap (hebloc.pieces)
                cond = "n_tokens_norm > 200"
            elif flag == "aramaic":
                cond = "aramaic IS NOT NULL"
            else:
                cond = f"len(list_filter(norm_flags, lambda f: starts_with(f, '{flag}'))) > 0"
            rows = con.execute(f"{base} WHERE {cond} ORDER BY hash(sent_id || '{seed}') LIMIT {per_flag}").df()
            if len(rows):
                parts += [f"### Targeted: `{flag}`", ""] + [_fmt(r) for r in rows.to_dict("records")]
    out.write_text("\n".join(parts), encoding="utf-8", newline="\n")
    return out
